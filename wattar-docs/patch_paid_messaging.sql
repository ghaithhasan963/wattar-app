CREATE OR REPLACE FUNCTION public.get_private_message_quote(p_conversation_id uuid)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_conversation public.private_conversations%ROWTYPE;
  v_settings public.private_message_settings%ROWTYPE;
  v_other_user uuid;
  v_free_used integer;
  v_friends boolean;
  v_sender_host boolean;
  v_other_host boolean;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'يجب تسجيل الدخول'; END IF;
  SELECT * INTO v_conversation
  FROM public.private_conversations
  WHERE id = p_conversation_id
    AND auth.uid() IN (user_one_id, user_two_id);
  IF NOT FOUND OR public.is_wattar_blocked_between(
    CASE WHEN auth.uid() = v_conversation.user_one_id THEN v_conversation.user_two_id ELSE v_conversation.user_one_id END
  ) THEN
    RAISE EXCEPTION 'المحادثة غير متاحة';
  END IF;

  v_other_user := CASE WHEN auth.uid() = v_conversation.user_one_id
    THEN v_conversation.user_two_id ELSE v_conversation.user_one_id END;
  SELECT * INTO v_settings FROM public.private_message_settings WHERE id = true;
  SELECT EXISTS (
    SELECT 1 FROM public.friend_requests f
    WHERE f.status = 'accepted'
      AND ((f.requester_id = auth.uid() AND f.recipient_id = v_other_user)
        OR (f.requester_id = v_other_user AND f.recipient_id = auth.uid()))
  ) INTO v_friends;
  SELECT EXISTS (SELECT 1 FROM public.host_program_members WHERE user_id = auth.uid() AND status = 'active')
    INTO v_sender_host;
  SELECT EXISTS (SELECT 1 FROM public.host_program_members WHERE user_id = v_other_user AND status = 'active')
    INTO v_other_host;
  SELECT count(*)::integer INTO v_free_used
  FROM public.private_messages m
  WHERE m.conversation_id = p_conversation_id
    AND m.sender_is_host_at_send = false;

  RETURN jsonb_build_object(
    'free_limit', v_settings.free_message_limit,
    'free_used', v_free_used,
    'free_remaining', CASE
      WHEN v_friends OR v_sender_host THEN NULL
      ELSE greatest(0, v_settings.free_message_limit - v_free_used)
    END,
    'price_coin', CASE
      WHEN v_friends OR v_sender_host OR v_free_used < v_settings.free_message_limit THEN 0
      ELSE v_settings.price_coin
    END,
    'host_commission_percent', v_settings.host_commission_percent,
    'recipient_is_host', v_other_host,
    'sender_is_host', v_sender_host,
    'is_friend', v_friends
  );
END;
$$;
REVOKE ALL ON FUNCTION public.get_private_message_quote(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_private_message_quote(uuid) TO authenticated;

DROP FUNCTION IF EXISTS public.create_private_conversation(uuid);
CREATE FUNCTION public.create_private_conversation(p_other_user_id uuid)
RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_one uuid;
  v_two uuid;
  v_conversation_id uuid;
BEGIN
  IF auth.uid() IS NULL OR p_other_user_id IS NULL OR p_other_user_id = auth.uid() THEN
    RAISE EXCEPTION 'المحادثة غير صالحة';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.users
    WHERE id = p_other_user_id AND status = 'active' AND adult_confirmed_at IS NOT NULL
      AND onboarding_completed_at IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'هذا الحساب غير مؤهل للمراسلة';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.users
    WHERE id = auth.uid() AND status = 'active' AND adult_confirmed_at IS NOT NULL
      AND onboarding_completed_at IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'الحساب غير مؤهل للمراسلة';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.user_blocks b
    WHERE (b.blocker_id = auth.uid() AND b.blocked_id = p_other_user_id)
       OR (b.blocker_id = p_other_user_id AND b.blocked_id = auth.uid())
  ) THEN
    RAISE EXCEPTION 'لا يمكن بدء محادثة مع هذا المستخدم';
  END IF;
  v_one := least(auth.uid(), p_other_user_id);
  v_two := greatest(auth.uid(), p_other_user_id);
  INSERT INTO public.private_conversations (user_one_id, user_two_id)
  VALUES (v_one, v_two)
  ON CONFLICT (user_one_id, user_two_id) DO UPDATE
    SET updated_at = public.private_conversations.updated_at
  RETURNING id INTO v_conversation_id;
  RETURN v_conversation_id;
END;
$$;
REVOKE ALL ON FUNCTION public.create_private_conversation(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_private_conversation(uuid) TO authenticated;

DROP FUNCTION IF EXISTS public.list_private_messages(uuid);
CREATE FUNCTION public.list_private_messages(p_conversation_id uuid)
RETURNS TABLE (
  message_id uuid,
  sender_id uuid,
  body text,
  created_at timestamptz,
  read_at timestamptz,
  username text,
  display_name text,
  avatar_url text,
  charged_coins bigint,
  host_commission_diamonds bigint
)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT m.id, m.sender_id, m.body, m.created_at, m.read_at,
         u.username::text, u.display_name::text, u.avatar_url,
         m.charged_coins, m.host_commission_diamonds
  FROM public.private_messages m
  JOIN public.private_conversations c ON c.id = m.conversation_id
  JOIN public.users u ON u.id = m.sender_id
  WHERE c.id = p_conversation_id
    AND auth.uid() IN (c.user_one_id, c.user_two_id)
    AND NOT EXISTS (
      SELECT 1 FROM public.user_blocks b
      WHERE (b.blocker_id = c.user_one_id AND b.blocked_id = c.user_two_id)
         OR (b.blocker_id = c.user_two_id AND b.blocked_id = c.user_one_id)
    )
  ORDER BY m.created_at DESC
  LIMIT 200;
$$;
REVOKE ALL ON FUNCTION public.list_private_messages(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.list_private_messages(uuid) TO authenticated;

DROP FUNCTION IF EXISTS public.send_private_message(uuid, text);
DROP FUNCTION IF EXISTS public.send_private_message(uuid, text, text);
CREATE FUNCTION public.send_private_message(
  p_conversation_id uuid,
  p_body text,
  p_idempotency_key text,
  p_confirmed_price_coin bigint
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_sender_id uuid := auth.uid();
  v_message_id uuid := gen_random_uuid();
  v_conversation public.private_conversations%ROWTYPE;
  v_settings public.private_message_settings%ROWTYPE;
  v_other_user_id uuid;
  v_free_used integer;
  v_charge bigint := 0;
  v_commission bigint := 0;
  v_friends boolean;
  v_sender_host boolean;
  v_other_host boolean;
  v_existing public.private_messages%ROWTYPE;
BEGIN
  IF v_sender_id IS NULL THEN RAISE EXCEPTION 'يجب تسجيل الدخول'; END IF;
  IF length(trim(coalesce(p_body, ''))) NOT BETWEEN 1 AND 2000 THEN
    RAISE EXCEPTION 'يجب أن تكون الرسالة بين حرف واحد و2000 حرف';
  END IF;
  IF length(trim(coalesce(p_idempotency_key, ''))) NOT BETWEEN 10 AND 70 THEN
    RAISE EXCEPTION 'مفتاح إرسال الرسالة غير صالح';
  END IF;
  IF p_confirmed_price_coin IS NULL OR p_confirmed_price_coin < 0 THEN
    RAISE EXCEPTION 'تأكيد سعر الرسالة غير صالح';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtext('private-message:' || p_idempotency_key));
  SELECT * INTO v_existing FROM public.private_messages
  WHERE idempotency_key = p_idempotency_key;
  IF FOUND THEN
    IF v_existing.sender_id <> v_sender_id
       OR v_existing.conversation_id <> p_conversation_id
       OR v_existing.body <> trim(p_body) THEN
      RAISE EXCEPTION 'مفتاح الإرسال مستخدم لرسالة أخرى';
    END IF;
    RETURN jsonb_build_object(
      'message_id', v_existing.id, 'charged_coins', v_existing.charged_coins,
      'host_commission_diamonds', v_existing.host_commission_diamonds,
      'already_processed', true
    );
  END IF;

  SELECT * INTO v_conversation
  FROM public.private_conversations
  WHERE id = p_conversation_id
    AND v_sender_id IN (user_one_id, user_two_id)
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'المحادثة غير متاحة'; END IF;
  v_other_user_id := CASE WHEN v_sender_id = v_conversation.user_one_id
    THEN v_conversation.user_two_id ELSE v_conversation.user_one_id END;
  IF public.is_wattar_blocked_between(v_other_user_id) THEN
    RAISE EXCEPTION 'المحادثة غير متاحة';
  END IF;
  PERFORM 1 FROM public.users
  WHERE id IN (v_sender_id, v_other_user_id)
  ORDER BY id
  FOR UPDATE;
  IF NOT EXISTS (
    SELECT 1 FROM public.users
    WHERE id = v_sender_id AND status = 'active' AND adult_confirmed_at IS NOT NULL
      AND onboarding_completed_at IS NOT NULL
  ) OR NOT EXISTS (
    SELECT 1 FROM public.users
    WHERE id = v_other_user_id AND status = 'active' AND adult_confirmed_at IS NOT NULL
      AND onboarding_completed_at IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'أحد الحسابين غير مؤهل للمراسلة';
  END IF;

  SELECT * INTO v_settings FROM public.private_message_settings WHERE id = true FOR SHARE;
  PERFORM 1 FROM public.host_program_members
  WHERE user_id IN (v_sender_id, v_other_user_id)
  ORDER BY user_id
  FOR SHARE;
  SELECT EXISTS (
    SELECT 1 FROM public.friend_requests f
    WHERE f.status = 'accepted'
      AND ((f.requester_id = v_sender_id AND f.recipient_id = v_other_user_id)
        OR (f.requester_id = v_other_user_id AND f.recipient_id = v_sender_id))
  ) INTO v_friends;
  SELECT EXISTS (SELECT 1 FROM public.host_program_members WHERE user_id = v_sender_id AND status = 'active')
    INTO v_sender_host;
  SELECT EXISTS (SELECT 1 FROM public.host_program_members WHERE user_id = v_other_user_id AND status = 'active')
    INTO v_other_host;

  SELECT count(*)::integer INTO v_free_used
  FROM public.private_messages m
  WHERE m.conversation_id = p_conversation_id
    AND m.sender_is_host_at_send = false;
  IF NOT v_friends AND NOT v_sender_host AND v_free_used >= v_settings.free_message_limit THEN
    v_charge := v_settings.price_coin;
    IF v_other_host THEN
      v_commission := floor(v_charge * v_settings.host_commission_percent / 100.0)::bigint;
    END IF;
  END IF;
  IF v_charge > p_confirmed_price_coin THEN
    RAISE EXCEPTION 'تغير سعر الرسالة أو انتهت الرسائل المجانية. حدّث السعر وأكد الإرسال من جديد.';
  END IF;

  IF v_charge > 0 THEN
    PERFORM public.record_wallet_transaction(
      v_sender_id, 'message_sent'::public.wallet_tx_type, -v_charge,
      'gold', NULL, 'private-message:' || p_idempotency_key || ':coin',
      'private_message', v_message_id,
      jsonb_build_object('conversation_id', p_conversation_id, 'recipient_id', v_other_user_id),
      'private-message-send'
    );
  END IF;
  IF v_commission > 0 THEN
    PERFORM public.record_wallet_transaction(
      v_other_user_id, 'message_commission'::public.wallet_tx_type, v_commission,
      'diamond', NULL, 'private-message:' || p_idempotency_key || ':host',
      'private_message', v_message_id,
      jsonb_build_object('conversation_id', p_conversation_id, 'sender_id', v_sender_id,
        'charged_coins', v_charge, 'commission_percent', v_settings.host_commission_percent),
      'private-message-send'
    );
    INSERT INTO public.user_notifications (
      user_id, actor_id, event_type, reference_id, title, body, route
    ) VALUES (
      v_other_user_id, v_sender_id, 'host_earning', v_message_id,
      'عمولة رسالة جديدة',
      format('أُضيفت %s Diamond إلى رصيدك من رسالة مدفوعة.', v_commission),
      '/(tabs)/wallet'
    )
    ON CONFLICT (user_id, event_type, reference_id) DO NOTHING;
  END IF;

  INSERT INTO public.private_messages (
    id, conversation_id, sender_id, body, charged_coins,
    host_commission_diamonds, sender_is_host_at_send, idempotency_key
  ) VALUES (
    v_message_id, p_conversation_id, v_sender_id, trim(p_body),
    v_charge, v_commission, v_sender_host, p_idempotency_key
  );
  UPDATE public.private_conversations SET updated_at = now()
  WHERE id = p_conversation_id;
  RETURN jsonb_build_object(
    'message_id', v_message_id, 'charged_coins', v_charge,
    'host_commission_diamonds', v_commission, 'free_remaining',
    CASE WHEN v_friends OR v_sender_host THEN NULL
      ELSE greatest(0, v_settings.free_message_limit - v_free_used - 1) END,
    'already_processed', false
  );
END;
$$;
REVOKE ALL ON FUNCTION public.send_private_message(uuid, text, text, bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.send_private_message(uuid, text, text, bigint) TO authenticated;

CREATE OR REPLACE FUNCTION public.send_host_intro_batch(p_limit integer DEFAULT 2)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_recipient_id uuid := auth.uid();
  v_settings public.private_message_settings%ROWTYPE;
  v_sent_today integer;
  v_limit integer;
  v_host record;
  v_template text;
  v_conversation_id uuid;
  v_message_id uuid;
  v_sent_ids uuid[] := ARRAY[]::uuid[];
BEGIN
  IF v_recipient_id IS NULL THEN RAISE EXCEPTION 'يجب تسجيل الدخول'; END IF;
  IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 5 THEN RAISE EXCEPTION 'حجم الدفعة غير صالح'; END IF;
  PERFORM 1 FROM public.users WHERE id = v_recipient_id FOR UPDATE;
  SELECT * INTO v_settings FROM public.private_message_settings WHERE id = true;
  IF NOT v_settings.host_outreach_enabled OR v_settings.host_intro_daily_limit = 0
     OR NOT EXISTS (
       SELECT 1 FROM public.users
       WHERE id = v_recipient_id AND role = 'user' AND status = 'active'
         AND adult_confirmed_at IS NOT NULL AND onboarding_completed_at IS NOT NULL
         AND host_message_opt_out = false
     ) THEN
    RETURN jsonb_build_object('sent_count', 0, 'message_ids', v_sent_ids);
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('host-outreach:' || v_recipient_id::text));
  SELECT count(*)::integer INTO v_sent_today
  FROM public.host_outreach_deliveries
  WHERE recipient_user_id = v_recipient_id
    AND sent_at >= date_trunc('day', now());
  v_limit := least(p_limit, v_settings.host_intro_daily_limit - v_sent_today);
  IF v_limit <= 0 THEN
    RETURN jsonb_build_object('sent_count', 0, 'message_ids', v_sent_ids);
  END IF;

  FOR v_host IN
    SELECT h.user_id
    FROM public.host_program_members h
    JOIN public.users u ON u.id = h.user_id AND u.role = 'user'
      AND u.status = 'active' AND u.adult_confirmed_at IS NOT NULL
      AND u.onboarding_completed_at IS NOT NULL
    WHERE h.status = 'active'
      AND h.user_id <> v_recipient_id
      AND NOT EXISTS (
        SELECT 1 FROM public.host_outreach_deliveries d
        WHERE d.host_user_id = h.user_id AND d.recipient_user_id = v_recipient_id
      )
      AND NOT EXISTS (
        SELECT 1 FROM public.user_blocks b
        WHERE (b.blocker_id = h.user_id AND b.blocked_id = v_recipient_id)
           OR (b.blocker_id = v_recipient_id AND b.blocked_id = h.user_id)
      )
      AND NOT EXISTS (
        SELECT 1 FROM public.friend_requests f
        WHERE f.status = 'accepted'
          AND ((f.requester_id = h.user_id AND f.recipient_id = v_recipient_id)
            OR (f.requester_id = v_recipient_id AND f.recipient_id = h.user_id))
      )
    ORDER BY h.approved_at, random()
    LIMIT v_limit
  LOOP
    SELECT body INTO v_template
    FROM public.host_intro_templates
    WHERE is_active
    ORDER BY random()
    LIMIT 1;
    IF v_template IS NULL THEN RAISE EXCEPTION 'لا توجد رسائل افتتاحية مفعلة'; END IF;

    INSERT INTO public.private_conversations (user_one_id, user_two_id)
    VALUES (least(v_host.user_id, v_recipient_id), greatest(v_host.user_id, v_recipient_id))
    ON CONFLICT (user_one_id, user_two_id) DO UPDATE
      SET updated_at = public.private_conversations.updated_at
    RETURNING id INTO v_conversation_id;

    v_message_id := gen_random_uuid();
    INSERT INTO public.private_messages (
      id, conversation_id, sender_id, body, sender_is_host_at_send, idempotency_key
    ) VALUES (
      v_message_id, v_conversation_id, v_host.user_id, v_template, true,
      'host-intro:' || v_host.user_id::text || ':' || v_recipient_id::text
    );
    UPDATE public.private_conversations SET updated_at = now()
    WHERE id = v_conversation_id;
    INSERT INTO public.host_outreach_deliveries (
      host_user_id, recipient_user_id, conversation_id, message_id
    ) VALUES (v_host.user_id, v_recipient_id, v_conversation_id, v_message_id);
    v_sent_ids := array_append(v_sent_ids, v_message_id);
    v_template := NULL;
  END LOOP;

  RETURN jsonb_build_object('sent_count', cardinality(v_sent_ids), 'message_ids', v_sent_ids);
END;
$$;
REVOKE ALL ON FUNCTION public.send_host_intro_batch(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.send_host_intro_batch(integer) TO authenticated;

COMMIT;
