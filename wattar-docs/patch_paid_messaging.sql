CREATE OR REPLACE FUNCTION public.admin_set_host_program_member(
  p_user_id uuid,
  p_active boolean,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_admin_id uuid := auth.uid();
  v_user public.users%ROWTYPE;
  v_before public.host_program_members%ROWTYPE;
  v_after public.host_program_members%ROWTYPE;
  v_reason text := nullif(btrim(p_reason), '');
BEGIN
  IF v_admin_id IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'غير مصرح بإدارة برنامج المضيفات';
  END IF;
  IF p_user_id IS NULL OR p_active IS NULL OR char_length(coalesce(v_reason, '')) NOT BETWEEN 3 AND 500 THEN
    RAISE EXCEPTION 'بيانات إدارة المضيفة غير مكتملة';
  END IF;
  SELECT * INTO v_user FROM public.users WHERE id = p_user_id FOR UPDATE;
  IF NOT FOUND OR v_user.status <> 'active' OR v_user.role <> 'user'
     OR v_user.adult_confirmed_at IS NULL OR v_user.onboarding_completed_at IS NULL THEN
    RAISE EXCEPTION 'يجب اختيار حساب مستخدم نشط ومؤكد العمر';
  END IF;

  SELECT * INTO v_before FROM public.host_program_members
  WHERE user_id = p_user_id FOR UPDATE;
  IF p_active THEN
    INSERT INTO public.host_program_members (user_id, status, approved_by, approved_at, updated_at)
    VALUES (p_user_id, 'active', v_admin_id, now(), now())
    ON CONFLICT (user_id) DO UPDATE
      SET status = 'active', approved_by = EXCLUDED.approved_by, updated_at = now()
    RETURNING * INTO v_after;
  ELSE
    IF NOT FOUND THEN RAISE EXCEPTION 'الحساب ليس عضوًا في برنامج المضيفات'; END IF;
    UPDATE public.host_program_members
    SET status = 'suspended', updated_at = now()
    WHERE user_id = p_user_id
    RETURNING * INTO v_after;
  END IF;

  INSERT INTO public.admin_audit_log (
    admin_id, action, target_type, target_id, before, after, metadata
  ) VALUES (
    v_admin_id,
    CASE WHEN p_active THEN 'approve'::public.audit_action_type
      ELSE 'suspend'::public.audit_action_type END,
    'host_program_member', p_user_id,
    CASE WHEN v_before.user_id IS NULL THEN NULL ELSE to_jsonb(v_before) END,
    to_jsonb(v_after),
    jsonb_build_object('reason', v_reason)
  );
  RETURN jsonb_build_object('user_id', p_user_id, 'status', v_after.status);
END;
$$;
REVOKE ALL ON FUNCTION public.admin_set_host_program_member(uuid, boolean, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_set_host_program_member(uuid, boolean, text) TO authenticated;

